-- Organizations: separate books. The main database holds the main books
-- (organization 1), the users, sessions and memberships; every other
-- organization has its own database (db_name) with the same schema, so its
-- accounts, entries and module data are kept apart. Applied to every
-- database; in an organization's own database these tables stay unused.
CREATE TABLE organizations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT        NOT NULL,
    kind       TEXT        NOT NULL DEFAULT 'business',
    db_name    TEXT        NOT NULL,
    status     TEXT        NOT NULL DEFAULT 'ready',
    message    TEXT        NOT NULL DEFAULT '',
    -- A starter chart of accounts still to create once it's ready, e.g. 'personal:CAD'.
    setup      TEXT        NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT organizations_name CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    CONSTRAINT organizations_kind CHECK (kind IN ('business', 'personal')),
    CONSTRAINT organizations_db_name CHECK (db_name ~ '^[a-z_][a-z0-9_]{0,62}$'),
    CONSTRAINT organizations_db_name_unique UNIQUE (db_name),
    CONSTRAINT organizations_status CHECK (status IN ('pending', 'ready', 'error'))
);
