-- Access to organizations other than the main one. (Access to the main books
-- stays users.role; 'none' means none.)
CREATE TABLE memberships (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    org_id  BIGINT NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    role    TEXT   NOT NULL,

    PRIMARY KEY (user_id, org_id),
    CONSTRAINT memberships_role CHECK (role IN ('admin', 'bookkeeper', 'viewer')),
    CONSTRAINT memberships_not_main CHECK (org_id <> 1)
);

ALTER TABLE users DROP CONSTRAINT users_role;
ALTER TABLE users ADD CONSTRAINT users_role CHECK (role IN ('admin', 'bookkeeper', 'viewer', 'none'));

-- The organization each session is working in.
ALTER TABLE sessions ADD COLUMN org_id BIGINT NOT NULL DEFAULT 1 REFERENCES organizations (id) ON DELETE CASCADE;
